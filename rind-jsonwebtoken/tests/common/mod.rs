use std::sync::OnceLock;

use aws_lc_rs::rand::SystemRandom;
#[cfg(not(target_arch = "arm"))]
use aws_lc_rs::signature::ECDSA_P384_SHA384_FIXED_SIGNING;
use aws_lc_rs::signature::{
    ECDSA_P256_SHA256_FIXED_SIGNING, EcdsaKeyPair, EcdsaSigningAlgorithm, Ed25519KeyPair, KeyPair,
};
use jsonwebtoken::crypto::aws_lc;
use jsonwebtoken::{Algorithm, DecodingKey, EncodingKey};
use rind::signing::{ecdsa, eddsa, rsa};

pub const HMAC: [Algorithm; 3] = [Algorithm::HS256, Algorithm::HS384, Algorithm::HS512];
pub const RSA: [Algorithm; 6] = [
    Algorithm::RS256,
    Algorithm::RS384,
    Algorithm::RS512,
    Algorithm::PS256,
    Algorithm::PS384,
    Algorithm::PS512,
];

/// A key pair for one algorithm, labelled with where it came from.
pub struct Key {
    pub algorithm: Algorithm,
    pub origin: &'static str,
    pub encoding: EncodingKey,
    pub decoding: DecodingKey,
}

impl Key {
    fn new(
        algorithm: Algorithm,
        origin: &'static str,
        encoding: EncodingKey,
        decoding: DecodingKey,
    ) -> Self {
        Self {
            algorithm,
            origin,
            encoding,
            decoding,
        }
    }

    pub fn label(&self) -> String {
        format!("{:?} from {}", self.algorithm, self.origin)
    }
}

/// Keys for every algorithm, generated by rind and, where it can export them, aws-lc-rs.
pub fn all() -> Vec<Key> {
    let mut keys = Vec::new();

    for algorithm in HMAC {
        let secret = b"a shared secret for rind-jsonwebtoken";
        keys.push(Key::new(
            algorithm,
            "a secret",
            EncodingKey::from_secret(secret),
            DecodingKey::from_secret(secret),
        ));
    }

    let p256 = ecdsa::SigningKey::<ecdsa::P256>::generate().unwrap();
    keys.push(Key::new(
        Algorithm::ES256,
        "rind",
        EncodingKey::from_ec_der(p256.to_pkcs8_der(&mut [0; 256]).unwrap()),
        DecodingKey::from_ec_der(&p256.private_key.public_key_uncompressed()),
    ));
    keys.push(aws_lc_ecdsa(
        Algorithm::ES256,
        &ECDSA_P256_SHA256_FIXED_SIGNING,
    ));

    #[cfg(not(target_arch = "arm"))]
    {
        let p384 = ecdsa::SigningKey::<ecdsa::P384>::generate().unwrap();
        keys.push(Key::new(
            Algorithm::ES384,
            "rind",
            EncodingKey::from_ec_der(p384.to_pkcs8_der(&mut [0; 256]).unwrap()),
            DecodingKey::from_ec_der(&p384.private_key.public_key_uncompressed()),
        ));
        keys.push(aws_lc_ecdsa(
            Algorithm::ES384,
            &ECDSA_P384_SHA384_FIXED_SIGNING,
        ));
    }

    let ed25519 = eddsa::Ed25519SigningKey::generate().unwrap();
    keys.push(Key::new(
        Algorithm::EdDSA,
        "rind",
        EncodingKey::from_ed_der(ed25519.to_pkcs8_der(&mut [0; 128]).unwrap()),
        DecodingKey::from_ed_der(&ed25519.public_key().as_bytes()),
    ));
    // aws-lc-rs writes PKCS#8 v2, which carries the public key too.
    let pkcs8 = Ed25519KeyPair::generate_pkcs8(&SystemRandom::new()).unwrap();
    let pair = Ed25519KeyPair::from_pkcs8(pkcs8.as_ref()).unwrap();
    keys.push(Key::new(
        Algorithm::EdDSA,
        "aws-lc-rs",
        EncodingKey::from_ed_der(pkcs8.as_ref()),
        DecodingKey::from_ed_der(pair.public_key().as_ref()),
    ));

    let (private, public) = rsa_key();
    // The components come from aws-lc-rs, so they check rind's parsing independently.
    let (n, e) = (aws_lc::DEFAULT_PROVIDER
        .key_utils
        .rsa_pub_components_from_public_key)(public)
    .unwrap();
    for algorithm in RSA {
        keys.push(Key::new(
            algorithm,
            "rind",
            EncodingKey::from_rsa_der(private),
            DecodingKey::from_rsa_der(public),
        ));
        keys.push(Key::new(
            algorithm,
            "rind, verified by modulus and exponent",
            EncodingKey::from_rsa_der(private),
            DecodingKey::from_rsa_raw_components(&n, &e),
        ));
    }

    keys
}

pub fn aws_lc_ecdsa(algorithm: Algorithm, signing: &'static EcdsaSigningAlgorithm) -> Key {
    let pkcs8 = EcdsaKeyPair::generate_pkcs8(signing, &SystemRandom::new()).unwrap();
    let pair = EcdsaKeyPair::from_pkcs8(signing, pkcs8.as_ref()).unwrap();
    Key::new(
        algorithm,
        "aws-lc-rs",
        EncodingKey::from_ec_der(pkcs8.as_ref()),
        DecodingKey::from_ec_der(pair.public_key().as_ref()),
    )
}

/// rind's RSA-2048 test key, as PKCS#1 private and public DER.
///
/// A fixture rather than a generated key, since armv7 cannot yet generate one.
pub fn rsa_key() -> (&'static [u8], &'static [u8]) {
    const PRIVATE: &[u8] = include_bytes!("../../../rind/src/high/rsa/rsa2048.der");
    static PUBLIC: OnceLock<Vec<u8>> = OnceLock::new();
    let public = PUBLIC.get_or_init(|| {
        rsa::SigningKey::from_pkcs1_der(PRIVATE)
            .unwrap()
            .public_key()
            .to_pkcs1_der(&mut [0; 512])
            .unwrap()
            .to_vec()
    });
    (PRIVATE, public)
}
